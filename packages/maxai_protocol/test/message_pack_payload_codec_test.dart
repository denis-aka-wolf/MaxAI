import 'dart:typed_data';

import 'package:maxai_protocol/maxai_protocol.dart';
import 'package:test/test.dart';

void main() {
  const codec = MessagePackPayloadCodec();

  test('roundtrips nested MAX-like payload', () {
    final payload = <String, Object?>{
      'chatId': 123456,
      'text': 'Привет, MAX!',
      'flags': <String, Object?>{'interactive': true, 'drafts': false},
      'items': <Object?>[1, 'two', null],
    };
    final decoded = codec.decode(codec.encode(payload));
    expect(decoded, equals(payload));
  });

  test('decodes MAX extension type 1 values in GET_QR response', () {
    // Реальный decompressed MessagePack payload из ответа opcode 288.
    final bytes = <int>[
      0x85,
      0xa7, 0x74, 0x72, 0x61, 0x63, 0x6b, 0x49, 0x64,
      0xd9, 0x24,
      0x62, 0x30, 0x32, 0x32, 0x64, 0x32, 0x64, 0x61, 0x2d,
      0x34, 0x34, 0x62, 0x36, 0x2d, 0x34, 0x32, 0x66, 0x34,
      0x2d, 0x38, 0x63, 0x38, 0x39, 0x2d, 0x35, 0x66, 0x38,
      0x65, 0x61, 0x65, 0x65, 0x39, 0x32, 0x36, 0x30, 0x62,
      0xa6, 0x71, 0x72, 0x4c, 0x69, 0x6e, 0x6b,
      0xd9, 0x39,
      0x68, 0x74, 0x74, 0x70, 0x73, 0x3a, 0x2f, 0x2f, 0x6d,
      0x61, 0x78, 0x2e, 0x72, 0x75, 0x2f, 0x3a, 0x61, 0x75,
      0x74, 0x68, 0x2f, 0x62, 0x30, 0x32, 0x32, 0x64, 0x32,
      0x64, 0x61, 0x2d, 0x34, 0x34, 0x62, 0x36, 0x2d, 0x34,
      0x32, 0x66, 0x34, 0x2d, 0x38, 0x63, 0x38, 0x39, 0x2d,
      0x35, 0x66, 0x38, 0x65, 0x61, 0x65, 0x65, 0x39, 0x32,
      0x36, 0x30, 0x62,
      0xa9, 0x65, 0x78, 0x70, 0x69, 0x72, 0x65, 0x73, 0x41,
      0x74, 0xc7, 0x09, 0x01, 0xd3, 0x00, 0x00, 0x01, 0xa1,
      0xea, 0x12, 0x20, 0xfb,
      0xaf, 0x70, 0x6f, 0x6c, 0x6c, 0x69, 0x6e, 0x67, 0x49,
      0x6e, 0x74, 0x65, 0x72, 0x76, 0x61, 0x6c, 0xc7, 0x03,
      0x01, 0xd1, 0x13, 0x88,
      0xa3, 0x74, 0x74, 0x6c, 0xc7, 0x05, 0x01, 0xd2, 0x00,
      0x01, 0xd4, 0xba,
    ];

    final decoded = codec.decode(Uint8List.fromList(bytes));
    expect(decoded, isA<Map>());
    final map = decoded as Map<Object?, Object?>;
    expect(map['expiresAt'], 1794928419067);
    expect(map['pollingInterval'], 5000);
    expect(map['ttl'], 119994);
    expect(map['trackId'], isA<String>());
    expect(map['qrLink'], startsWith('https://max.ru/:auth/'));

    final qr = QrLoginRequest.fromPayload(map);
    expect(qr.expiresAt, 1794928419067);
    expect(qr.pollingInterval, 5000);
    expect(qr.ttl, 119994);
  });

  test('preserves unknown extension types instead of returning null', () {
    // ext8, length=1, type=42, one-byte payload=7.
    final decoded = codec.decode(Uint8List.fromList([0xc7, 0x01, 0x2a, 0x07]));
    expect(decoded, isA<MessagePackExtension>());
    final extension = decoded as MessagePackExtension;
    expect(extension.type, 42);
    expect(extension.data, [7]);
  });
}
